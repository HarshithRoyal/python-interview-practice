# Integer
age = 25

# Float
salary = 75000.50

# String
name = "Harshith"

# Boolean
is_employed = True

# Check data types
print(type(age))
print(type(salary))
print(type(name))
print(type(is_employed))

# Multiple assignment
x, y, z = 10, 20, 30

print(x)
print(y)
print(z)

# Swap two variables
a = 5
b = 10

a, b = b, a

print(a)
print(b)
